# Regenerate after adding national spirits to common/ideas.
# Reset visible and hidden national spirits; laws and advisors are separate systems.
$modRoot = Split-Path -Parent $PSScriptRoot
$ideas = [System.Collections.Generic.SortedSet[string]]::new([System.StringComparer]::Ordinal)
foreach ($file in Get-ChildItem -LiteralPath (Join-Path $modRoot 'common/ideas') -Filter '*.txt' -Recurse) {
    $tokens = [regex]::Matches([System.IO.File]::ReadAllText($file.FullName), '#[^\r\n]*|"(?:\\.|[^"\\])*"|[{}=]|[^\s{}=#"]+') |
        Where-Object { -not $_.Value.StartsWith('#') }
    $blocks = [System.Collections.Generic.List[string]]::new()
    for ($i = 0; $i -lt $tokens.Count; $i++) {
        if ($tokens[$i].Value -eq '{') {
            $name = if ($i -ge 2 -and $tokens[$i-1].Value -eq '=') { $tokens[$i-2].Value.Trim('"') } else { '' }
            if ($blocks.Count -eq 2 -and $blocks[0] -eq 'ideas' -and $blocks[1] -in @('country', 'hidden_ideas') -and $name -notin @('endtimes_cabal', 'CSTO_member')) {
                [void]$ideas.Add($name)
            }
            $blocks.Add($name)
        } elseif ($tokens[$i].Value -eq '}') {
            if ($blocks.Count -eq 0) { throw "Unbalanced idea file: $($file.FullName)" }
            $blocks.RemoveAt($blocks.Count - 1)
        }
    }
    if ($blocks.Count -ne 0) { throw "Unbalanced idea file: $($file.FullName)" }
}
if ($ideas.Count -eq 0) { throw 'No country ideas found' }
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Generated by tools/Generate-EndtimesIdeaReset.ps1 from visible and hidden national spirits.')
$lines.Add('# Removing an inactive idea is a no-op. Cabal and CSTO membership are deliberately excluded.')
$lines.Add('endtimes_clear_national_spirits_except_cabal_and_csto = {')
$lines.Add("`tremove_ideas = {")
foreach ($idea in $ideas) { $lines.Add("`t`t$idea") }
$lines.Add("`t}")
$lines.Add('}')
[System.IO.File]::WriteAllLines((Join-Path $modRoot 'common/scripted_effects/endtimes_idea_reset.txt'), $lines, [System.Text.UTF8Encoding]::new($false))
Write-Output "Generated reset for $($ideas.Count) country ideas; Cabal and CSTO excluded."
