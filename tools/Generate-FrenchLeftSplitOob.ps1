# Prepare deterministic army reassignment for the optional French split.
# Selected starting formations are spawned with script IDs so the split can
# remove the originals even if they have since moved away from their home state.
# On repeat runs, the generated FRC OOB is the recorded regional roster.
$modRoot = Split-Path -Parent $PSScriptRoot
$encoding = [Text.UTF8Encoding]::new($false)
$regionStates = @(56,54,55,305,59)
$regionProvinces = [Collections.Generic.HashSet[int]]::new()
foreach ($state in $regionStates) {
    $file = Get-ChildItem (Join-Path $modRoot 'history/states') -Filter "$state-*"
    $body = [regex]::Match([IO.File]::ReadAllText($file.FullName),'(?s)\bprovinces\s*=\s*\{([^}]+)\}').Groups[1].Value
    foreach ($number in [regex]::Matches($body,'\b\d+\b')) { [void]$regionProvinces.Add([int]$number.Value) }
}
function Get-OobBlocks([string]$Text,[string]$Key) {
    foreach ($start in [regex]::Matches($Text,"(?m)^\s*" + [regex]::Escape($Key) + '\s*=\s*\{')) {
        $depth = 0
        foreach ($token in [regex]::Matches($Text.Substring($start.Index),'"(?:\\.|[^"\\])*"|#[^\r\n]*|[{}]')) {
            if ($token.Value -eq '{') { $depth++ }
            elseif ($token.Value -eq '}') {
                $depth--
                if ($depth -eq 0) {
                    [pscustomobject]@{ Start = $start.Index; Length = $token.Index+1; Text = $Text.Substring($start.Index,$token.Index+1) }
                    break
                }
            }
        }
        if ($depth -ne 0) { throw "Unbalanced source block: $Key" }
    }
}
function Save-Text([string]$RelativePath,[string]$Text) {
    [IO.File]::WriteAllText((Join-Path $modRoot $RelativePath),$Text + "`r`n",$encoding)
}
$nameDefinitions = [IO.File]::ReadAllText((Join-Path $modRoot 'common/units/names_divisions/FRA_names_divisions.txt'))
$effects = [Collections.Generic.List[string]]::new()
$effects.Add('# Generated by tools/Generate-FrenchLeftSplitOob.ps1. Historical army roster only.')
$sources = @(
    @{ Source = 'FRA_2000_nsb'; Suffix = 'nsb'; Mode = 1 },
    @{ Source = 'FRA_2000_nonnsb'; Suffix = 'legacy_2024'; Mode = 2 },
    @{ Source = 'FRA_2017_nonnsb'; Suffix = 'legacy_2026'; Mode = 3 }
)
foreach ($entry in $sources) {
    $sourcePath = Join-Path $modRoot "history/units/$($entry.Source).txt"
    $sourceText = [IO.File]::ReadAllText($sourcePath)
    $hook = "rev_fra_tag_regional_army_$($entry.Suffix)"
    $oobName = "FRC_split_army_$($entry.Suffix)"
    $alreadyPrepared = $sourceText.Contains("$hook = yes")
    $rosterText = if ($alreadyPrepared) { [IO.File]::ReadAllText((Join-Path $modRoot "history/units/$oobName.txt")) } else { $sourceText }
    $selected = @(Get-OobBlocks $rosterText 'division' | Where-Object {
        $regionProvinces.Contains([int][regex]::Match($_.Text,'\blocation\s*=\s*(\d+)').Groups[1].Value)
    })
    if ($selected.Count -eq 0) { throw "No regional formations: $($entry.Source)" }
    $templates = [Collections.Generic.List[string]]::new()
    $usedTemplates = [Collections.Generic.HashSet[string]]::new()
    $units = [Collections.Generic.List[string]]::new()
    $effects.Add("$hook = {")
    $effects.Add("`tset_variable = { rev_fra_regional_oob_mode = $($entry.Mode) }")
    $unitNumber = 0
    foreach ($record in $selected) {
        $unitNumber++
        $unit = $record.Text.Trim()
        $templateName = [regex]::Match($unit,'division_template\s*=\s*"([^"]+)"').Groups[1].Value
        $template = @(Get-OobBlocks $sourceText 'division_template' | Where-Object {
            [regex]::Match($_.Text,'\bname\s*=\s*"([^"]+)"').Groups[1].Value -eq $templateName
        })
        if ($template.Count -ne 1) { throw "Missing or duplicate source template: $templateName" }
        $orderedName = [regex]::Match($unit,'(?s)division_name\s*=\s*\{.*?name_order\s*=\s*(\d+).*?\}')
        if ($orderedName.Success) {
            $order = $orderedName.Groups[1].Value
            $group = [regex]::Match($template[0].Text,'division_names_group\s*=\s*(\w+)').Groups[1].Value
            $groupBlock = @(Get-OobBlocks $nameDefinitions $group)
            if ($groupBlock.Count -ne 1) { throw "Missing division-name group: $group" }
            $nameMatch = [regex]::Match($groupBlock[0].Text,'(?m)^\s*' + $order + '\s*=\s*\{\s*"([^"]+)"')
            if (-not $nameMatch.Success) { throw "Missing ordered name: $group / $order" }
            $name = $nameMatch.Groups[1].Value.Replace('%d',$order).Replace('%s',$order)
            $unit = $unit.Remove($orderedName.Index,$orderedName.Length).Insert($orderedName.Index,('name = "' + $name + '"'))
        }
        if ($usedTemplates.Add($templateName)) {
            $templates.Add([regex]::Replace($template[0].Text.Trim(),'(?m)^\s*division_names_group\s*=\s*\S+\s*$',''))
        }
        $units.Add($unit)
        $body = $unit.Substring($unit.IndexOf('{')+1,$unit.LastIndexOf('}')-$unit.IndexOf('{')-1)
        # Remove comments while preserving quoted names, then serialize the OOB
        # division body into create_unit's documented division string.
        $body = [regex]::Replace($body,'"(?:\\.|[^"\\])*"|#[^\r\n]*',{ param($match) if ($match.Value.StartsWith('#')) { '' } else { $match.Value } })
        $serialized = $body.Replace('\','\\').Replace('"','\"').Replace("`r",' ').Replace("`n",' ').Trim()
        $location = [regex]::Match($unit,'\blocation\s*=\s*(\d+)').Groups[1].Value
        $scriptId = 9905600 + $unitNumber
        $effects.Add("`tcreate_unit = {")
        $effects.Add("`t`towner = FRA")
        $effects.Add("`t`tid = $scriptId")
        $effects.Add("`t`tprioritize_location = $location")
        $effects.Add(('        division = "' + $serialized + '"'))
        $effects.Add("`t}")
    }
    $effects.Add('}')
    $entry.Count = $unitNumber
    Save-Text "history/units/$oobName.txt" ("# Regional formations from $($entry.Source).txt; loaded only at the split.`r`n" + ($templates -join "`r`n`r`n") + "`r`nunits = {`r`n" + ($units -join "`r`n") + "`r`n}")
    if (-not $alreadyPrepared) {
        # Leave all other divisions, templates, stockpiles and production intact.
        foreach ($record in ($selected | Sort-Object Start -Descending)) {
            $sourceText = $sourceText.Remove($record.Start,$record.Length)
        }
        $instantEffects = @(Get-OobBlocks $sourceText 'instant_effect')
        if ($instantEffects.Count) {
            $last = $instantEffects[-1]
            $insertAt = $last.Start + $last.Length - 1
            $sourceText = $sourceText.Insert($insertAt,"`r`n`t# Tag the regional starting formations for deterministic reassignment.`r`n`t$hook = yes`r`n")
        } else {
            $sourceText += "`r`ninstant_effect = { $hook = yes }`r`n"
        }
        [IO.File]::WriteAllText($sourcePath,$sourceText,$encoding)
    }
    Write-Output "$($entry.Source): $unitNumber tagged regional formations"
}
$effects.Add('rev_fra_reassign_regional_army = {')
foreach ($entry in $sources) {
    $keyword = if ($entry.Mode -eq 1) { 'if' } else { 'else_if' }
    $effects.Add("`t$keyword = {")
    $effects.Add("`t`tlimit = { check_variable = { rev_fra_regional_oob_mode = $($entry.Mode) } }")
    for ($i = 1; $i -le $entry.Count; $i++) {
        $scriptId = 9905600 + $i
        $effects.Add("`t`tdelete_unit = { id = $scriptId disband = no }")
    }
    $effects.Add("`t`tFRC = { load_oob = FRC_split_army_$($entry.Suffix) }")
    $effects.Add("`t}")
}
$effects.Add('}')
Save-Text 'common/scripted_effects/rev_french_left_split_army_effects.txt' ($effects -join "`r`n")
